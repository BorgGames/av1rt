"""Generates the AV1_COMP state mirror used by the e7 (rate control) differential tests.

shim_e7_fields.txt lists "<C# type> <path from cpi>" per line. Every entry becomes one 8-byte
field (int64 or double) of a flat E7State struct, so the C and C# layouts cannot drift.
"extra <name>" lines add an unmapped int64 input that the shim / harness handle by hand.
Outputs:
  * tools/oracle/shim/shim_e7_fields.h          E7_FIELDS(I, D) / E7_EXTRA_FIELDS(I) X-macros
  * tests/Av1rt.Tests/RateControl/E7State.g.cs  the C# struct and its Load/Store

Run: python tools/oracle/shim/gen_e7_fields.py
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.normpath(os.path.join(here, "..", "..", ".."))

entries = []
with open(os.path.join(here, "shim_e7_fields.txt")) as f:
    for line in f:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        cs_type, path = line.split()
        if cs_type == "extra":
            name = path
        else:
            name = path.replace(".", "_").replace("[", "_").replace("]", "")
        entries.append((cs_type, path, name))
mapped = [e for e in entries if e[0] != "extra"]
extras = [e for e in entries if e[0] == "extra"]


def c_path(p):
    p = "cpi->" + p
    for ptr in ("ppi.", "cyclic_refresh.", "common.seq_params."):
        p = p.replace("cpi->" + ptr, "cpi->" + ptr[:-1] + "->")
    return p


with open(os.path.join(here, "shim_e7_fields.h"), "w", newline="\n") as f:
    f.write("/* Generated by gen_e7_fields.py from shim_e7_fields.txt: do not edit. */\n")
    f.write("/* E7State layout: every entry in file order, int64_t or double. */\n")
    f.write("#define E7_ALL_FIELDS(I, D, X) \\\n")
    for cs_type, path, name in entries:
        if cs_type == "extra":
            f.write(f"  X({name}) \\\n")
        elif cs_type == "double":
            f.write(f"  D({name}, {c_path(path)}) \\\n")
        else:
            f.write(f"  I({name}, {c_path(path)}) \\\n")
    f.write("\n")

load = {
    "int": "(int)s.{n}", "uint": "(uint)s.{n}", "ulong": "(ulong)s.{n}", "long": "s.{n}",
    "double": "s.{n}", "bool": "s.{n} != 0", "byte": "(byte)s.{n}", "short": "(short)s.{n}",
}
store = {
    "int": "{p}", "uint": "{p}", "ulong": "(long){p}", "long": "{p}", "double": "{p}",
    "bool": "{p} ? 1 : 0", "byte": "{p}", "short": "{p}",
}

out = os.path.join(repo, "tests", "Av1rt.Tests", "RateControl", "E7State.g.cs")
with open(out, "w", newline="\n") as f:
    f.write("// <auto-generated> by tools/oracle/shim/gen_e7_fields.py: do not edit. </auto-generated>\n")
    f.write("using System.Runtime.InteropServices;\nusing Av1rt.Aom;\n\n")
    f.write("namespace Av1rt.Tests.RateControl;\n\n")
    f.write("[StructLayout(LayoutKind.Sequential)]\ninternal partial struct E7State\n{\n")
    for cs_type, path, name in entries:
        f.write(f"    public {'double' if cs_type == 'double' else 'long'} {name};\n")
    f.write("\n    internal static readonly string[] FieldNames =\n    {\n")
    for _, _, name in entries:
        f.write(f"        \"{name}\",\n")
    f.write("    };\n\n")
    f.write("    internal readonly void Load(AV1_COMP cpi)\n    {\n        E7State s = this;\n")
    for cs_type, path, name in mapped:
        f.write(f"        cpi.{path} = {load[cs_type].format(n=name)};\n")
    f.write("    }\n\n")
    f.write("    internal void Store(AV1_COMP cpi)\n    {\n")
    for cs_type, path, name in mapped:
        f.write(f"        {name} = {store[cs_type].format(p='cpi.' + path)};\n")
    f.write("    }\n}\n")
print("wrote", out)
