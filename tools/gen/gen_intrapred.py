"""Generates src/Av1rt/Aom/aom_dsp/intrapred.c.cs (port of libaom aom_dsp/intrapred.c).

The per-size predictors are defined in C through the intra_pred_sized / intra_pred_allsizes /
intra_pred_square macros; this expands them into real methods with the exact C names plus the
RTCD forwarders (aom_dsp_rtcd.h maps every name to its _c version in the pure-C build).
Usage: python gen_intrapred.py <output path>
"""
import sys

# Order of intra_pred_allsizes expansion (CONFIG_REALTIME_ONLY && CONFIG_AV1_DECODER, so the
# full rectangular list is compiled).
SQUARE = [(4, 4), (8, 8), (16, 16), (32, 32), (64, 64)]
RECT = [(4, 8), (8, 4), (8, 16), (16, 8), (16, 32), (32, 16), (32, 64), (64, 32),
        (4, 16), (16, 4), (8, 32), (32, 8), (16, 64), (64, 16)]
ALL = SQUARE + RECT

# Families ported (see the [subset] note for smooth_v, smooth_h and paeth).
ALLSIZES = ['v', 'h', 'smooth', 'dc_128', 'dc_left', 'dc_top']

# dc rect predictors: explicit functions in C (shift1, multiplier).
DC_RECT = {
    (4, 8): (2, 'DC_MULTIPLIER_1X2'), (8, 4): (2, 'DC_MULTIPLIER_1X2'),
    (4, 16): (2, 'DC_MULTIPLIER_1X4'), (16, 4): (2, 'DC_MULTIPLIER_1X4'),
    (8, 16): (3, 'DC_MULTIPLIER_1X2'), (16, 8): (3, 'DC_MULTIPLIER_1X2'),
    (8, 32): (3, 'DC_MULTIPLIER_1X4'), (32, 8): (3, 'DC_MULTIPLIER_1X4'),
    (16, 32): (4, 'DC_MULTIPLIER_1X2'), (32, 16): (4, 'DC_MULTIPLIER_1X2'),
    (16, 64): (4, 'DC_MULTIPLIER_1X4'), (64, 16): (4, 'DC_MULTIPLIER_1X4'),
    (32, 64): (5, 'DC_MULTIPLIER_1X2'), (64, 32): (5, 'DC_MULTIPLIER_1X2'),
}
DC_RECT_ORDER = [(4, 8), (8, 4), (4, 16), (16, 4), (8, 16), (16, 8), (8, 32), (32, 8),
                 (16, 32), (32, 16), (16, 64), (64, 16), (32, 64), (64, 32)]

PARAMS = 'Ptr<byte> dst, int stride, Ptr<byte> above, Ptr<byte> left'
ARGS = 'dst, stride, above, left'

HEAD = '''// Port of libaom aom_dsp/intrapred.c
// The per-size wrappers below (intra_pred_sized / intra_pred_allsizes / intra_pred_square
// macro expansions) and their RTCD forwarders are generated by a script; the kernels are
// hand-ported.

global using static Av1rt.Aom.intrapred;

using System.Diagnostics;
using System.Runtime.CompilerServices;

namespace Av1rt.Aom;

internal static partial class intrapred
{
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void v_predictor(Ptr<byte> dst, int stride, int bw, int bh,
                                    Ptr<byte> above, Ptr<byte> left)
    {
        int r;

        for (r = 0; r < bh; r++)
        {
            memcpy(dst, above, bw);
            dst += stride;
        }
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void h_predictor(Ptr<byte> dst, int stride, int bw, int bh,
                                    Ptr<byte> above, Ptr<byte> left)
    {
        int r;

        for (r = 0; r < bh; r++)
        {
            memset(dst, left[r], bw);
            dst += stride;
        }
    }

    // [subset] abs_diff, paeth_predictor_single, paeth_predictor: PAETH_PRED is never
    // selected in the realtime subset (the nonrd intra mode list is DC/V/H/SMOOTH).

    // [port] divide_round(value, bits) macro.
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static uint divide_round(uint value, int bits) =>
        (value + (1u << ((bits) - 1))) >> (bits);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void smooth_predictor(Ptr<byte> dst, int stride, int bw,
                                         int bh, Ptr<byte> above,
                                         Ptr<byte> left)
    {
        byte below_pred = left[bh - 1];   // estimated by bottom-left pixel
        byte right_pred = above[bw - 1];  // estimated by top-right pixel
        Ptr<byte> sm_weights_w = new Ptr<byte>(smooth_weights, bw - 4);
        Ptr<byte> sm_weights_h = new Ptr<byte>(smooth_weights, bh - 4);
        // scale = 2 * 2^SMOOTH_WEIGHT_LOG2_SCALE
        int log2_scale = 1 + SMOOTH_WEIGHT_LOG2_SCALE;
        ushort scale = (1 << SMOOTH_WEIGHT_LOG2_SCALE);
        // sm_weights_sanity_checks(sm_weights_w, sm_weights_h, scale, log2_scale + sizeof(*dst))
        Debug.Assert(sm_weights_w[0] < scale);
        Debug.Assert(sm_weights_h[0] < scale);
        Debug.Assert(scale - sm_weights_w[bw - 1] < scale);
        Debug.Assert(scale - sm_weights_h[bh - 1] < scale);
        Debug.Assert(log2_scale + sizeof(byte) < 31);  // ensures no overflow when calculating predictor.
        int r;
        for (r = 0; r < bh; ++r)
        {
            int c;
            for (c = 0; c < bw; ++c)
            {
                // [port] C builds the 4-element arrays pixels[] = { above[c], below_pred,
                // left[r], right_pred } and weights[] (uint8_t) per pixel and sums
                // weights[i] * pixels[i]; unrolled here without the arrays.
                byte w0 = sm_weights_h[r];
                byte w1 = (byte)(scale - sm_weights_h[r]);
                byte w2 = sm_weights_w[c];
                byte w3 = (byte)(scale - sm_weights_w[c]);
                uint this_pred = 0;
                Debug.Assert(scale >= sm_weights_h[r] && scale >= sm_weights_w[c]);
                this_pred += (uint)(w0 * above[c]);
                this_pred += (uint)(w1 * below_pred);
                this_pred += (uint)(w2 * left[r]);
                this_pred += (uint)(w3 * right_pred);
                dst[c] = (byte)divide_round(this_pred, log2_scale);
            }
            dst += stride;
        }
    }

    // [subset] smooth_v_predictor, smooth_h_predictor: SMOOTH_V_PRED / SMOOTH_H_PRED are
    // never selected in the realtime subset.

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void dc_128_predictor(Ptr<byte> dst, int stride, int bw,
                                         int bh, Ptr<byte> above,
                                         Ptr<byte> left)
    {
        int r;

        for (r = 0; r < bh; r++)
        {
            memset(dst, (byte)128, bw);
            dst += stride;
        }
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void dc_left_predictor(Ptr<byte> dst, int stride, int bw,
                                          int bh, Ptr<byte> above,
                                          Ptr<byte> left)
    {
        int i, r, expected_dc, sum = 0;

        for (i = 0; i < bh; i++) sum += left[i];
        expected_dc = (sum + (bh >> 1)) / bh;

        for (r = 0; r < bh; r++)
        {
            memset(dst, (byte)expected_dc, bw);
            dst += stride;
        }
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void dc_top_predictor(Ptr<byte> dst, int stride, int bw,
                                         int bh, Ptr<byte> above,
                                         Ptr<byte> left)
    {
        int i, r, expected_dc, sum = 0;

        for (i = 0; i < bw; i++) sum += above[i];
        expected_dc = (sum + (bw >> 1)) / bw;

        for (r = 0; r < bh; r++)
        {
            memset(dst, (byte)expected_dc, bw);
            dst += stride;
        }
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void dc_predictor(Ptr<byte> dst, int stride, int bw, int bh,
                                     Ptr<byte> above, Ptr<byte> left)
    {
        int i, r, expected_dc, sum = 0;
        int count = bw + bh;

        for (i = 0; i < bw; i++)
        {
            sum += above[i];
        }
        for (i = 0; i < bh; i++)
        {
            sum += left[i];
        }

        expected_dc = (sum + (count >> 1)) / count;

        for (r = 0; r < bh; r++)
        {
            memset(dst, (byte)expected_dc, bw);
            dst += stride;
        }
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static int divide_using_multiply_shift(int num, int shift1,
                                                   int multiplier, int shift2)
    {
        int interm = num >> shift1;
        return interm * multiplier >> shift2;
    }

    // The constants (multiplier and shifts) for a given block size are obtained
    // as follows:
    // - Let sum_w_h =  block width + block height.
    // - Shift 'sum_w_h' right until we reach an odd number. Let the number of
    // shifts for that block size be called 'shift1' (see the parameter in
    // dc_predictor_rect() function), and let the odd number be 'd'. [d has only 2
    // possible values: d = 3 for a 1:2 rect block and d = 5 for a 1:4 rect
    // block].
    // - Find multipliers for (i) dividing by 3, and (ii) dividing by 5,
    // using the "Algorithm 1" in:
    // http://ieeexplore.ieee.org/stamp/stamp.jsp?tp=&arnumber=1467632
    // by ensuring that m + n = 16 (in that algorithm). This ensures that our 2nd
    // shift will be 16, regardless of the block size.

    // Note: For low bitdepth, assembly code may be optimized by using smaller
    // constants for smaller block sizes, where the range of the 'sum' is
    // restricted to fewer bits.

    private const int DC_MULTIPLIER_1X2 = 0x5556;
    private const int DC_MULTIPLIER_1X4 = 0x3334;

    private const int DC_SHIFT2 = 16;

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void dc_predictor_rect(Ptr<byte> dst, int stride, int bw,
                                          int bh, Ptr<byte> above,
                                          Ptr<byte> left, int shift1,
                                          int multiplier)
    {
        int sum = 0;

        for (int i = 0; i < bw; i++)
        {
            sum += above[i];
        }
        for (int i = 0; i < bh; i++)
        {
            sum += left[i];
        }

        int expected_dc = divide_using_multiply_shift(
            sum + ((bw + bh) >> 1), shift1, multiplier, DC_SHIFT2);
        Debug.Assert(expected_dc < (1 << 8));

        for (int r = 0; r < bh; r++)
        {
            memset(dst, (byte)expected_dc, bw);
            dst += stride;
        }
    }
'''


def method(name, body):
    return (f'    internal static void {name}_c({PARAMS})\n'
            f'    {{\n'
            f'        {body}\n'
            f'    }}\n\n'
            f'    internal static void {name}({PARAMS}) =>\n'
            f'        {name}_c({ARGS});\n')


def main(out):
    parts = [HEAD]
    parts.append('\n    // ---- dc_predictor_rect sizes (explicit functions in C) ----\n\n')
    for (w, h) in DC_RECT_ORDER:
        shift1, mult = DC_RECT[(w, h)]
        name = f'aom_dc_predictor_{w}x{h}'
        parts.append(method(name, f'dc_predictor_rect(dst, stride, {w}, {h}, above, left, {shift1}, {mult});'))
        parts.append('\n')
    parts.append('    // ---- intra_pred_allsizes(v, h, smooth, dc_128, dc_left, dc_top) ----\n')
    parts.append('    // [subset] intra_pred_allsizes(smooth_v), (smooth_h), (paeth): never selected.\n\n')
    for fam in ALLSIZES:
        for (w, h) in ALL:
            name = f'aom_{fam}_predictor_{w}x{h}'
            parts.append(method(name, f'{fam}_predictor(dst, stride, {w}, {h}, above, left);'))
            parts.append('\n')
    parts.append('    // ---- intra_pred_square(dc) ----\n\n')
    for (w, h) in SQUARE:
        name = f'aom_dc_predictor_{w}x{h}'
        parts.append(method(name, f'dc_predictor(dst, stride, {w}, {h}, above, left);'))
        parts.append('\n')
    text = ''.join(parts).rstrip('\n') + '\n}\n'
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write(text)


if __name__ == '__main__':
    main(sys.argv[1])
